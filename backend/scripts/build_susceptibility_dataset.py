"""Phase 20 — builds a real presence/pseudo-absence dataset for landslide
SUSCEPTIBILITY modeling (not the label-free positive-only Phase 14 dataset
`build_feature_dataset.py` already produces, which is untouched by this
script).

Every positive row is a real registered LandslideEvent inside the given
bounding box. Every negative row is a real coordinate + real historical date
generated by `app.services.negative_sampling_service` — buffered away from
known events, kept only where real DEM/land-cover rasters actually cover the
point, and stratified against the study area's own real terrain
distribution. Rows missing any critical feature (a rainfall window, slope,
or land cover) are DROPPED, never imputed — a dropped-row count is recorded
in the output metadata, not hidden.

Usage:
    python scripts/build_susceptibility_dataset.py \
        --min-lat 28.4 --min-lon 75.4 --max-lat 33.3 --max-lon 81.1 \
        --output data/processed/susceptibility_dataset.csv
"""
import argparse
import csv
import json
import sys
from datetime import datetime
from pathlib import Path
from types import SimpleNamespace

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.database import SessionLocal  # noqa: E402
from app.models.landslide_event import LandslideEvent  # noqa: E402
from app.services.feature_engineering_service import (  # noqa: E402
    FEATURE_SCHEMA_VERSION,
    build_feature_vector,
)
from app.services.negative_sampling_service import (  # noqa: E402
    DEFAULT_BUFFER_KM,
    DEFAULT_RATIO,
    compute_terrain_distribution,
    generate_negative_samples,
)

DEFAULT_OUTPUT = "data/processed/susceptibility_dataset.csv"
DATASET_VERSION = "phase20-v1"

FEATURE_COLUMNS = [
    "source_event_id",
    "label",
    "source_type",
    "latitude",
    "longitude",
    "as_of",
    "rainfall_24h",
    "rainfall_72h",
    "rainfall_7d",
    "rainfall_30d",
    "antecedent_rainfall_index",
    "elevation_m",
    "slope_degrees",
    "aspect_degrees",
    "landcover_category",
    "historical_landslide_count",
    "historical_landslide_density_per_km2",
]

# `rainfall_available` only means "a nearby station was found" — it does NOT
# guarantee every individual window (24h/72h/7d/30d/antecedent) actually has
# data, since a real station can have a gap in one window and not another.
# So critical-feature validity is checked at the level of the actual numeric
# fields a training row needs, never just the coarser boolean flags.
CRITICAL_FEATURES = ("terrain_available", "landcover_available")
CRITICAL_NUMERIC_FIELDS = (
    "rainfall_24h", "rainfall_72h", "rainfall_7d", "rainfall_30d", "antecedent_rainfall_index",
    "elevation_m", "slope_degrees",
)


def _has_all_critical_fields(features: dict) -> bool:
    if not all(features[key] for key in CRITICAL_FEATURES):
        return False
    return all(features.get(field) is not None for field in CRITICAL_NUMERIC_FIELDS)


def _row_from_features(features: dict, *, label: int, source_type: str, source_event_id) -> dict:
    return {
        "source_event_id": source_event_id,
        "label": label,
        "source_type": source_type,
        "latitude": features["input"]["lat"],
        "longitude": features["input"]["lon"],
        "as_of": features["input"]["as_of"],
        **{col: features[col] for col in FEATURE_COLUMNS if col in features},
    }


def main():
    parser = argparse.ArgumentParser(description="Build a real presence/pseudo-absence susceptibility dataset")
    parser.add_argument("--min-lat", type=float, required=True)
    parser.add_argument("--min-lon", type=float, required=True)
    parser.add_argument("--max-lat", type=float, required=True)
    parser.add_argument("--max-lon", type=float, required=True)
    parser.add_argument("--output", default=DEFAULT_OUTPUT)
    parser.add_argument("--ratio", type=int, default=DEFAULT_RATIO, help="negatives per positive")
    parser.add_argument("--buffer-km", type=float, default=DEFAULT_BUFFER_KM)
    parser.add_argument("--boundary-path", default=None, help="Optional real state/india boundary GeoJSON to restrict negatives to")
    parser.add_argument("--allowed-region-names", default=None, help="Comma-separated region names (matching the boundary file's name property) negatives must fall inside, e.g. 'Uttarakhand,Himachal Pradesh'")
    parser.add_argument("--stratify-sample-size", type=int, default=500, help="Random points sampled to compute the real target slope/landcover distribution")
    parser.add_argument("--no-stratify", action="store_true", help="Skip stratification — accept any buffer/boundary/coverage-passing candidate")
    parser.add_argument("--random-seed", type=int, default=None)
    parser.add_argument(
        "--negatives-cache",
        default=None,
        help="Reuse an exact negative-sample set from scripts/extract_chirps_rainfall.py's cache CSV "
        "(point_id,latitude,longitude,as_of) instead of generating a fresh random draw — required "
        "whenever rainfall was pre-extracted only for specific negative coordinates.",
    )
    args = parser.parse_args()

    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    metadata_path = output_path.with_suffix(".metadata.json")
    boundary_path = Path(args.boundary_path) if args.boundary_path else None
    allowed_region_names = (
        {name.strip() for name in args.allowed_region_names.split(",")} if args.allowed_region_names else None
    )

    db = SessionLocal()
    try:
        events = (
            db.query(LandslideEvent)
            .filter(
                LandslideEvent.latitude.between(args.min_lat, args.max_lat),
                LandslideEvent.longitude.between(args.min_lon, args.max_lon),
            )
            .order_by(LandslideEvent.id)
            .all()
        )

        print("=" * 60)
        print("BHUSURAKSHA AI - SUSCEPTIBILITY DATASET BUILD (Phase 20)")
        print("=" * 60)
        print(f"Bounding box: ({args.min_lat},{args.min_lon}) - ({args.max_lat},{args.max_lon})")
        print(f"Real positive events in bbox: {len(events)}")

        rows = []
        dropped_missing_features = 0

        for event in events:
            as_of = event.event_date or event.created_at
            features = build_feature_vector(db, lat=event.latitude, lon=event.longitude, as_of=as_of)
            if not _has_all_critical_fields(features):
                dropped_missing_features += 1
                continue
            rows.append(_row_from_features(features, label=1, source_type="external_real", source_event_id=event.id))

        positive_dates = [event.event_date or event.created_at for event in events]
        target_distribution = None
        if not args.no_stratify and positive_dates:
            print(f"\nSampling {args.stratify_sample_size} random points to compute the real target terrain distribution...")
            target_distribution = compute_terrain_distribution(
                args.min_lat, args.min_lon, args.max_lat, args.max_lon,
                sample_size=args.stratify_sample_size, random_seed=args.random_seed,
            )
            print(f"  slope distribution: {target_distribution.get('slope')}")
            print(f"  landcover distribution: {target_distribution.get('landcover')}")

        negative_stats = None
        if args.negatives_cache:
            print(f"\nReusing exact negative samples from {args.negatives_cache} (skipping fresh generation)...")
            negatives = []
            with open(args.negatives_cache, newline="", encoding="utf-8") as f:
                for row in csv.DictReader(f):
                    negatives.append(SimpleNamespace(
                        latitude=float(row["latitude"]), longitude=float(row["longitude"]),
                        as_of=datetime.fromisoformat(row["as_of"]), point_id=row["point_id"],
                    ))
            print(f"  loaded {len(negatives)} cached negative sample(s)")

            for negative in negatives:
                features = build_feature_vector(db, lat=negative.latitude, lon=negative.longitude, as_of=negative.as_of)
                if not _has_all_critical_fields(features):
                    dropped_missing_features += 1
                    continue
                rows.append(_row_from_features(features, label=0, source_type="derived", source_event_id=negative.point_id))
        elif positive_dates:
            negative_count = len(events) * args.ratio
            print(f"\nGenerating {negative_count} pseudo-absence (negative) samples...")
            negatives, negative_stats = generate_negative_samples(
                db,
                min_lat=args.min_lat, min_lon=args.min_lon, max_lat=args.max_lat, max_lon=args.max_lon,
                positive_dates=positive_dates, count=negative_count, buffer_km=args.buffer_km,
                boundary_path=boundary_path, allowed_region_names=allowed_region_names,
                target_distribution=target_distribution,
                random_seed=args.random_seed,
            )
            print(f"  {negative_stats}")

            for i, negative in enumerate(negatives):
                features = build_feature_vector(db, lat=negative.latitude, lon=negative.longitude, as_of=negative.as_of)
                if not _has_all_critical_fields(features):
                    dropped_missing_features += 1
                    continue
                rows.append(_row_from_features(features, label=0, source_type="derived", source_event_id=f"negative_{i}"))
        else:
            print("\nNo real positive events in this bounding box — skipping negative generation (there is no real date range to draw from).")

        with open(output_path, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=FEATURE_COLUMNS)
            writer.writeheader()
            writer.writerows(rows)

        metadata = {
            "dataset_version": DATASET_VERSION,
            "feature_schema_version": FEATURE_SCHEMA_VERSION,
            "generated_at": datetime.utcnow().isoformat(),
            "bounding_box": {"min_lat": args.min_lat, "min_lon": args.min_lon, "max_lat": args.max_lat, "max_lon": args.max_lon},
            "positive_count": sum(1 for r in rows if r["label"] == 1),
            "negative_count": sum(1 for r in rows if r["label"] == 0),
            "rows_dropped_missing_features": dropped_missing_features,
            "negative_sampling_methodology": {
                "buffer_km": args.buffer_km,
                "requested_ratio": args.ratio,
                "stratified": target_distribution is not None,
                "target_distribution": target_distribution,
                "boundary_path": str(boundary_path) if boundary_path else None,
                "allowed_region_names": sorted(allowed_region_names) if allowed_region_names else None,
                "as_of_assignment": "uniform random date within the real positive events' date range in this bbox",
                "generation_stats": negative_stats,
                "negatives_cache_reused": args.negatives_cache,
            },
            "note": (
                "Positive rows (label=1, source_type=external_real) are real registered LandslideEvent "
                "records. Negative rows (label=0, source_type=derived) are real coordinates/dates but a "
                "CONSTRUCTED 'no landslide recorded here' assertion, not ground truth. This is a dataset "
                "for susceptibility modeling, NOT itself a trained model. See docs/ML_LIMITATIONS.md."
            ),
        }
        with open(metadata_path, "w", encoding="utf-8") as f:
            json.dump(metadata, f, indent=2, default=str)

        print(f"\nWrote {len(rows)} row(s) ({metadata['positive_count']} positive, {metadata['negative_count']} negative) to {output_path}")
        print(f"Dropped {dropped_missing_features} row(s) missing a critical feature (never imputed).")
        print(f"Wrote metadata to {metadata_path}")
    finally:
        db.close()


if __name__ == "__main__":
    main()
